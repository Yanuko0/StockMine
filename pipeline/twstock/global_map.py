def _rows(block: str, n: int) -> list[list[str]]:
    out = []
    for line in block.strip().splitlines():
        parts = [p.strip() for p in line.split("|")]
        if len(parts) == n and parts[0]:
            out.append(parts)
    return out


def themes() -> list[dict]:
    """展開成程式好用的格式。"""
    res = []
    for t in THEMES:
        res.append({
            "id": t["id"], "name": t["name"],
            "foreign": [{"sym": s, "name": nm, "sub": sub} for s, nm, sub in _rows(t["foreign"], 3)],
            "tw": [{"code": c, "name": nm, "tier": int(tier), "sub": sub} for c, nm, tier, sub in _rows(t["tw"], 4)],
        })
    return res


def market_of(sym: str) -> str:
    if sym.endswith(".T"):
        return "JP"
    if sym.endswith(".KS") or sym.endswith(".KQ"):
        return "KR"
    if sym.endswith(".SS") or sym.endswith(".SZ"):
        return "CN"
    if "." in sym:
        return "EU"
    return "US"
